    private void updatePreview() {
    if (logic == null) {
        jLabelPreview.setIcon(null);
        return;
    }

    try {
        BufferedImage raw = logic.renderMessages(
                jTextField1.getText(),
                jTextField2.getText(),
                0xFF00FFFF,   // OSRS chat cyan
                2             // line gap
        );

        BufferedImage scaled =
                RuneScapeChatLogic.scaleNearest(raw, 1);

        jLabelPreview.setIcon(new ImageIcon(scaled));

    } catch (IllegalArgumentException ex) {
        jLabelPreview.setIcon(null);
    }
}
    
    
private void updateAlignment() {
    if (logic == null) {
        jLabel1.setText("RuneScape font failed to load.");
        return;
    }

    try {
        RuneScapeChatLogic.Alignment a =
                logic.checkAlignment(
                        jTextField1.getText(),
                        jTextField2.getText()
                );

        if (a.exact()) {
            jLabel1.setText("EXACT");
            jLabelSuggestion.setText(" ");
            return;
        }

        jLabel1.setText(logic.describeAlignment(
                jTextField1.getText(),
                jTextField2.getText()
        ));

        jLabelSuggestion.setText(
                logic.describeWidthSuggestions(a.errorPx())
        );

    } catch (IllegalArgumentException ex) {
        jLabel1.setText(ex.getMessage());
        jLabelSuggestion.setText(" ");
    }
    }
